# Enrich entities.json
updated_count = 0
not_found = []

for eid, ent in entities.items():
    cur_ar = ent.get("label_ar")
    cur_bn = ent.get("label_bn")
    if cur_ar and cur_bn:
        continue
    
    clean_k = re.sub(r"^[^:]+:", "", eid).lower()
    norm_k = re.sub(r"[^a-z0-9]", "", clean_k)
    label_norm = re.sub(r"[^a-z0-9]", "", (ent.get("label_en") or "").lower())
    
    match = None
    # direct slug lookup
    if clean_k in MASTER_MAP:
        match = MASTER_MAP[clean_k]
    else:
        # normalized lookup
        for mk, val in MASTER_MAP.items():
            if re.sub(r"[^a-z0-9]", "", mk) in (norm_k, label_norm):
                match = val
                break
                
    if match:
        ent["label_ar"] = match[0]
        ent["label_bn"] = match[1]
        updated_count += 1
    else:
        not_found.append((eid, ent.get("type"), ent.get("label_en")))

print(f"Updated {updated_count} entities with authentic Arabic & Bengali labels.")
print(f"Remaining unmatched: {len(not_found)}")
if not_found:
    print("Unmatched:", not_found)

